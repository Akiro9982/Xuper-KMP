package com.xuperclean.core.net

import java.io.ByteArrayInputStream
import java.security.KeyStore
import java.security.SecureRandom
import java.security.cert.CertificateException
import java.security.cert.CertificateFactory
import java.security.cert.X509Certificate
import javax.net.ssl.SSLContext
import javax.net.ssl.SSLSocketFactory
import javax.net.ssl.TrustManagerFactory
import javax.net.ssl.X509TrustManager

/**
 * Confianza TLS ampliada para televisores y teléfonos antiguos.
 *
 * El portal, el perfil remoto y varios CDN usan certificados emitidos por las CA
 * nuevas de Let's Encrypt (`ISRG Root X2`, intermedios `Root YE`/`YR`) y de Google
 * Trust Services (`GTS Root R4`). Android 7 y anteriores no traen esas raíces en su
 * almacén del sistema y la conexión falla con:
 *
 *   java.security.cert.CertPathValidatorException: Trust anchor for certification path not found.
 *
 * Se combinan las CA del sistema con estas raíces públicas empaquetadas, sin desactivar
 * la validación ni la comprobación de hostname de OkHttp.
 */
object LegacyTls {

    data class Config(
        val socketFactory: SSLSocketFactory,
        val trustManager: X509TrustManager,
    )

    val config: Config by lazy { create() }

    private fun create(): Config {
        val system = trustManager(null)
        val extraStore = KeyStore.getInstance(KeyStore.getDefaultType()).apply {
            load(null, null)
            val factory = CertificateFactory.getInstance("X.509")
            PEM_ROOTS.forEachIndexed { index, pem ->
                val cert = factory.generateCertificate(
                    ByteArrayInputStream(pem.trimIndent().toByteArray(Charsets.US_ASCII)),
                )
                setCertificateEntry("xuper-extra-$index", cert)
            }
        }
        val extra = trustManager(extraStore)
        val combined = CombinedTrustManager(system, extra)
        val context = SSLContext.getInstance("TLS").apply {
            init(null, arrayOf(combined), SecureRandom())
        }
        return Config(context.socketFactory, combined)
    }

    private fun trustManager(store: KeyStore?): X509TrustManager {
        val factory = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
        factory.init(store)
        return factory.trustManagers.filterIsInstance<X509TrustManager>().first()
    }

    private class CombinedTrustManager(
        private val system: X509TrustManager,
        private val extra: X509TrustManager,
    ) : X509TrustManager {

        override fun checkClientTrusted(chain: Array<out X509Certificate>, authType: String) {
            system.checkClientTrusted(chain, authType)
        }

        override fun checkServerTrusted(chain: Array<out X509Certificate>, authType: String) {
            try {
                system.checkServerTrusted(chain, authType)
            } catch (systemError: CertificateException) {
                try {
                    extra.checkServerTrusted(chain, authType)
                } catch (_: CertificateException) {
                    throw systemError
                }
            }
        }

        override fun getAcceptedIssuers(): Array<X509Certificate> =
            system.acceptedIssuers + extra.acceptedIssuers
    }

